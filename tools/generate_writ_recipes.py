"""Generate the Writ recipe subset from the pinned Forever client-table extract."""

import argparse
from collections import Counter, defaultdict
import hashlib
import json
from pathlib import Path
import re


ROOT = Path(__file__).resolve().parents[1] / "MerchantsFavourOptimiser"
SHA256 = "836cf70e39fa6b947a1eb01682d08a51d48d99dc694226fc5ffc57d37dc4f744"


def generate(snapshot):
    if hashlib.sha256(snapshot).hexdigest() != SHA256:
        raise ValueError("Recipe snapshot does not match the pinned Forever extract")
    data = json.loads(snapshot)
    writs = (ROOT / "WritData.lua").read_text(encoding="utf-8")
    targets = {int(item) for item in re.findall(r"\{id = (\d+), qty =", writs)}
    by_output = defaultdict(list)
    for profession in data["professions"]:
        for recipe in profession["recipes"]:
            if recipe.get("p"):
                by_output[recipe["p"][0]].append((profession, recipe))

    pending, checked, rows = set(targets), set(), {}
    while pending:
        item = pending.pop()
        if item in checked:
            continue
        checked.add(item)
        choices = by_output[item]
        if len(choices) != 1:
            continue
        profession, recipe = choices[0]
        # An audited single-cast transmute is the only supported long cooldown.
        if (recipe.get("x") or not recipe.get("r") or len(recipe["p"]) != 2
                or (recipe.get("cd") and recipe["i"] != 17187)):
            continue
        reagents = Counter()
        for reagent, quantity in recipe["r"]:
            if reagent < 1 or quantity < 1:
                raise ValueError(f"Invalid reagent for spell {recipe['i']}")
            reagents[reagent] += quantity
        pending.update(reagents)
        reagent_fields = ", ".join(f"[{reagent}]={qty}" for reagent, qty in sorted(reagents.items()))
        fields = [
            f"spell={recipe['i']}",
            f"profession={json.dumps(profession['name'])}",
            f"line={profession['id']}",
            f"output={recipe['p'][1]}",
        ]
        # Trainer ranks marked t/e are borrowed or estimated by the source.
        if recipe["s"] == "i" and recipe.get("l"):
            fields.append(f"skill={recipe['l']}")
        if recipe.get("f"):
            fields.append("station=" + json.dumps(recipe["f"]))
        if recipe.get("t"):
            fields.append(f"tools={len(recipe['t'])}")
        if recipe.get("cd"):
            fields.append("cooldown=true")
        fields.append("reagents={" + reagent_fields + "}")
        rows[item] = "  [%d] = {%s}," % (item, ", ".join(fields))
    return "\n".join([
        "-- Generated by tools/generate_writ_recipes.py. See WRIT_SOURCES.md.",
        "MFO_WritRecipes = {",
        *(rows[item] for item in sorted(rows)),
        "}",
        "",
    ])


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("snapshot", type=Path)
    parser.add_argument("--check", action="store_true")
    arguments = parser.parse_args()
    generated = generate(arguments.snapshot.read_bytes())
    output = ROOT / "WritRecipes.lua"
    if arguments.check:
        if output.read_text(encoding="utf-8") != generated:
            raise SystemExit("WritRecipes.lua differs from the pinned snapshot")
    else:
        output.write_text(generated, encoding="utf-8", newline="\n")
